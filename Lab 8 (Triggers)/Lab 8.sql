-- INSTEAD OF TRIGGERS)

CREATE VIEW EMP_DEPT_VIEW AS
SELECT e.EMPLOYEE_ID, e.FIRST_NAME, d.DEPARTMENT_NAME
FROM EMPLOYEES e
JOIN DEPARTMENTS d
ON e.DEPARTMENT_ID = d.DEPARTMENT_ID;

CREATE OR REPLACE TRIGGER trg_emp_dept_insert
INSTEAD OF INSERT ON EMP_DEPT_VIEW
FOR EACH ROW
BEGIN
    INSERT INTO EMPLOYEES (EMPLOYEE_ID, FIRST_NAME)
    VALUES (:NEW.EMPLOYEE_ID, :NEW.FIRST_NAME);
END;
/

CREATE VIEW EMP_SAL_VIEW AS
SELECT EMPLOYEE_ID, SALARY
FROM EMPLOYEES;

CREATE OR REPLACE TRIGGER trg_salary_restrict_update
INSTEAD OF UPDATE ON EMP_SAL_VIEW
FOR EACH ROW
BEGIN
    IF :NEW.SALARY < :OLD.SALARY * 0.80 THEN
        RAISE_APPLICATION_ERROR(-20004, 'Salary cannot be reduced more than 20%');
    ELSE
        UPDATE EMPLOYEES
        SET SALARY = :NEW.SALARY
        WHERE EMPLOYEE_ID = :OLD.EMPLOYEE_ID;
    END IF;
END;
/


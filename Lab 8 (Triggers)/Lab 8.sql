CREATE TABLE EMP_AUDIT (
    EMPLOYEE_ID NUMBER,
    OLD_SALARY NUMBER,
    NEW_SALARY NUMBER,
    ACTION_TYPE VARCHAR2(10),
    ACTION_DATE DATE
);

CREATE OR REPLACE TRIGGER trg_emp_audit
AFTER INSERT OR UPDATE OR DELETE ON EMPLOYEES
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO EMP_AUDIT
        VALUES (:NEW.EMPLOYEE_ID, NULL, :NEW.SALARY, 'INSERT', SYSDATE);

    ELSIF UPDATING THEN
        INSERT INTO EMP_AUDIT
        VALUES (:OLD.EMPLOYEE_ID, :OLD.SALARY, :NEW.SALARY, 'UPDATE', SYSDATE);

    ELSIF DELETING THEN
        INSERT INTO EMP_AUDIT
        VALUES (:OLD.EMPLOYEE_ID, :OLD.SALARY, NULL, 'DELETE', SYSDATE);
    END IF;
END;
/


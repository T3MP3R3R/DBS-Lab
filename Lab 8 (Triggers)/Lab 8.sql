CREATE VIEW EMP_VIEW_SIMPLE AS
SELECT EMPLOYEE_ID, FIRST_NAME FROM EMPLOYEES;

CREATE OR REPLACE TRIGGER trg_backup
AFTER INSERT OR UPDATE OR DELETE ON EMPLOYEES
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO EMP_BACKUP VALUES (:NEW.EMPLOYEE_ID, :NEW.FIRST_NAME, :NEW.SALARY);

    ELSIF UPDATING THEN
        UPDATE EMP_BACKUP
        SET SALARY = :NEW.SALARY
        WHERE EMPLOYEE_ID = :OLD.EMPLOYEE_ID;

    ELSIF DELETING THEN
        DELETE FROM EMP_BACKUP
        WHERE EMPLOYEE_ID = :OLD.EMPLOYEE_ID;
    END IF;
END;
/

